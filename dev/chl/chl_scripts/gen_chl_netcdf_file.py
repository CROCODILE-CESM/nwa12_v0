import numpy as np
import xarray as xr

def gen_chl_dummy_dataset(output_path):
    # === Coordinates ===
    lon = np.linspace(0, 39, 40)  # You can use actual values if available
    lat = np.linspace(0, 29, 30)
    time = np.array([15.5, 45, 74.5, 105, 135.5, 166, 196.5, 227.5, 258, 288.5, 319, 349.5])

    # === Placeholder data for CHL_A (all fill values) ===
    fill_value = -1.e+34
    chl_a_data = np.empty((len(time), len(lat), len(lon)), dtype=np.float32)

    # === xarray Dataset ===
    ds = xr.Dataset(
        {
            "CHL_A": xr.DataArray(
                chl_a_data,
                dims=["TIME", "LAT", "LON"],
                coords={"TIME": time, "LAT": lat, "LON": lon},
                attrs={
                    "long_name": "CHL_A = monthly mean",
                    "units": "mg/m^3",
                    "_FillValue": fill_value,
                    "missing_value": fill_value,
                }
            )
        },
        coords={
            "LON": xr.DataArray(
                lon, dims="LON", attrs={
                    "units": "degrees_east",
                    "axis": "X"
                }
            ),
            "LAT": xr.DataArray(
                lat, dims="LAT", attrs={
                    "units": "degrees_north",
                    "axis": "Y"
                }
            ),
            "TIME": xr.DataArray(
                time, dims="TIME", attrs={
                    "units": "days since 0001-01-01 00:00:00",
                    "calendar": "NOLEAP",
                    "modulo": " ",
                    "axis": "T",
                    "cartesian_axis": "T"
                }
            )
        },
        attrs={  # Global attributes
            "title": "SeaWiFS Chlorophyll Climatology (1997–2010)",
            "institution": "Generated by xarray",
            "source": "Simulated data",
            "history": "Created for demonstration"
        }
    )
    # === Save to NetCDF with TIME as unlimited ===
    ds.to_netcdf(output_path, unlimited_dims=["TIME"])

    print(f"Wrote emptyNetCDF file to:\n{output_path}")
    return ds
